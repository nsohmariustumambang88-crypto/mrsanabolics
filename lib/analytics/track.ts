import 'server-only';

import { randomBytes } from 'node:crypto';
import { prisma } from '@/lib/prisma';
import { asBoolean, getSettingsSafe } from '@/lib/settings';

/*
  The visit counter.

  What this records is deliberately thin: a random token, the paths it asked for, the host that
  sent it, and a two-letter country from the CDN when there is one. What it does NOT record is
  the thing every analytics product records by default — the IP address. Not stored, not hashed,
  not passed to this file at all. A hash is not anonymisation for a value with four billion
  possibilities; it is plaintext with an extra step, which is why lib/ip-hash.ts refuses to
  produce one without a salt and why nothing here calls it.

  The visitor token is generated by the server from randomBytes and is derived from nothing
  about the person. Two people on the same connection are two visitors; one person who clears
  their cookies is two visitors. That is the correct trade: the count is slightly wrong and
  nobody is identified by it.

  Every entry point is gated on the `analytics_enabled` setting and every one of them returns
  cleanly when it is off. "Off" has to mean nothing is written, not that a screen stops showing
  what is still being collected.
*/

/** 32 hex characters. Random, server-generated, and derived from nothing about the visitor. */
export function newVisitorToken(): string {
  return randomBytes(16).toString('hex');
}

/** A token is only ever accepted in the shape we issue it. */
export function isVisitorToken(value: string | null | undefined): value is string {
  return typeof value === 'string' && /^[0-9a-f]{32}$/.test(value);
}

/*
  Referrers are reduced to a hostname before they go anywhere near the database.

  A full referrer URL routinely carries the previous page's query string, and that query string
  belongs to somebody else — their search terms, their session ids, occasionally their email
  address in a click-tracking parameter. Storing it would be collecting a third party's data by
  accident. The host is the only part that answers the question we are actually asking, which is
  "where did this person come from".

  Defined here rather than in the route because both the route and any future server-side caller
  must reduce it the same way; two copies of this would drift and one of them would store a URL.
*/
export function referrerHost(referrer: string | null | undefined): string | null {
  if (!referrer) return null;
  try {
    const host = new URL(referrer).hostname.toLowerCase();
    return host ? host.replace(/^www\./, '').slice(0, 120) : null;
  } catch {
    return null;
  }
}

/** Two-letter uppercase, or nothing. CDNs emit placeholders for unknown, and those are not countries. */
export function normaliseCountry(value: string | null | undefined): string | null {
  if (!value) return null;
  const code = value.trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(code)) return null;
  if (code === 'XX' || code === 'T1') return null;
  return code;
}

/** Lower-cased and space-collapsed, so "  Test  E "  and "test e" are one term. */
export function normaliseTerm(term: string): string {
  return term.trim().toLowerCase().replace(/\s+/g, ' ');
}

async function enabled(): Promise<boolean> {
  const settings = await getSettingsSafe();
  return asBoolean(settings.analytics_enabled);
}

/* --------------------------------------------------------------------- views */

export type RecordViewInput = {
  token: string;
  path: string;
  referrer?: string | null;
  country?: string | null;
};

/**
 * Upsert the visitor and append one page view.
 *
 * This is a single nested write, not an interactive transaction. `prisma.$transaction(async
 * tx => …)` holds a connection open across several round trips, and against Neon behind
 * PgBouncer that is how the admin writes deadlocked — see CLAUDE.md. A nested create is atomic
 * on its own and costs one round trip.
 *
 * `source` is written on create only. It is the acquisition source: where this person first
 * arrived from. Overwriting it on every view would turn every returning visitor into "direct"
 * and destroy the only number on the screen that says anything about marketing.
 */
export async function recordView(input: RecordViewInput): Promise<void> {
  if (!isVisitorToken(input.token)) return;
  if (!(await enabled())) return;

  const path = input.path.slice(0, 512);
  const host = referrerHost(input.referrer);
  const country = normaliseCountry(input.country);
  const now = new Date();

  await prisma.visitor.upsert({
    where: { token: input.token },
    create: {
      token: input.token,
      country,
      source: host ?? 'direct',
      viewCount: 1,
      firstSeenAt: now,
      lastSeenAt: now,
      lastPath: path,
      pageViews: { create: { path, referrer: host } },
    },
    update: {
      viewCount: { increment: 1 },
      lastSeenAt: now,
      lastPath: path,
      /* Geo can legitimately change — travel, a VPN switched on. Latest wins, and an absent
         header never blanks a country we already knew. */
      ...(country ? { country } : {}),
      pageViews: { create: { path, referrer: host } },
    },
  });
}

/* ------------------------------------------------------------------ searches */

export type RecordSearchInput = {
  token?: string | null;
  term: string;
  resultCount: number;
};

/**
 * Record what someone typed into the search box and how many products came back.
 *
 * Linked to the visitor when the token is one we issued, and written unlinked when it is not.
 * An unlinked search is still the most useful row in this whole feature — a zero-result term is
 * a customer saying, in their own words, what they came for and could not find — so a missing
 * cookie must never be a reason to drop it.
 */
export async function recordSearch(input: RecordSearchInput): Promise<void> {
  const term = input.term.trim().slice(0, 200);
  if (!term) return;
  if (!(await enabled())) return;

  /* Looked up rather than connected by token: `connect` on an unknown token throws, and a
     failed analytics write must never be the reason a search page errors. */
  let visitorId: string | null = null;
  if (isVisitorToken(input.token)) {
    const visitor = await prisma.visitor.findUnique({
      where: { token: input.token },
      select: { id: true },
    });
    visitorId = visitor?.id ?? null;
  }

  await prisma.searchQuery.create({
    data: {
      term,
      normalized: normaliseTerm(term),
      resultCount: Math.max(0, Math.floor(input.resultCount)),
      visitorId,
    },
  });
}
